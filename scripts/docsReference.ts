/**
 * The syntax reference, generated from the same registry the parser uses.
 *
 *   bun run docs:reference
 *
 * If this file and the engine disagree, the engine wins. Regenerate it.
 */

import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { listAttributes } from "../src/core/syntax/attributeRegistry";
import { ATTRIBUTE_DESCRIPTIONS } from "../src/core/syntax/attributeDocs";

const ROOT = join(import.meta.dir, "..");
const OUT = join(ROOT, "docs", "syntax", "reference.md");

const lines: string[] = [
  "# Attribute reference",
  "",
  "Generated from `src/core/syntax/attributes.ts` by `bun run docs:reference`.",
  "Do not edit this file by hand.",
  "",
  "| Attribute | Aliases | Type | Group | Notes |",
  "| --- | --- | --- | --- | --- |",
];

for (const attribute of listAttributes()) {
  const aliases = attribute.aliases.join(", ");
  const notes = ATTRIBUTE_DESCRIPTIONS[attribute.key] ?? "";
  lines.push(
    `| \`${attribute.key}\` | ${aliases} | ${attribute.type} | ${attribute.group} | ${notes} |`,
  );
}

lines.push("");
lines.push(
  "Unknown attributes are kept and warned about, not dropped. A typo never loses text.",
);

await mkdir(join(ROOT, "docs", "syntax"), { recursive: true });
await writeFile(OUT, lines.join("\n"), "utf8");
console.log(
  `Wrote ${OUT.replace(ROOT, ".")}: ${listAttributes().length} attributes.`,
);
