export const BUILTIN_TRANSLATIONS: Readonly<
  Record<string, TranslationTable>
> = { en: EN, nl: NL };

export const DEFAULT_LANGUAGE = "en";

export function translate(
  language: string | null | undefined,
  key: string,
  params: Readonly<Record<string, string | number>> = {},
  overrides: Readonly<Record<string, TranslationTable>> = {},
): string {
  const code = (language ?? DEFAULT_LANGUAGE).toLowerCase();
  const fallback = BUILTIN_TRANSLATIONS[DEFAULT_LANGUAGE] ?? {};
  const table = {
    ...(BUILTIN_TRANSLATIONS[code] ?? {}),
    ...(overrides[code] ?? overrides[DEFAULT_LANGUAGE] ?? {}),
  };
  const template = table[key] ?? fallback[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}
